#!/usr/bin/env node
// Daily drift check: compares what your notes and process CLAIM against reality.
//   - default branch on origin vs the deploy target's checkout HEAD (merged but not deployed?)
//   - health endpoints
//   - open PRs older than STALE_PR_DAYS
//   - leftover worktrees
// Writes the verdict into MEMORY_DIR/DRIFT_REPORT_FILE so the advisor terminal sees it at session
// start. Run it from cron; `--stdout` prints the report instead of writing it.
//
//   node tools/drift-check.mjs [--stdout] [--strict]
//
// Exit code is 0 even on drift (the report is the output); --strict exits 1 on drift for CI use.
//
// Config: see .env.example (MAIN_WORKTREE required; PROD_SSH / HEALTH_URL / MEMORY_DIR optional).
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadConfig, requireKeys } from "../lib/env.mjs";

const DAY_MS = 864e5;

/** PURE: open PRs older than `days`. */
export function findStalePRs(prs, now, days) {
  return (prs || []).filter((p) => now - Date.parse(p.createdAt) > days * DAY_MS);
}

/**
 * PURE: turn the gathered facts into a list of drift findings (empty = in sync).
 * facts: { mainHead, prodHead|null, behind, health: {url: status}, prListError, stalePRs, staleDays, defaultBranch }
 */
export function evaluateDrift(f) {
  const drift = [];
  if (String(f.mainHead).startsWith("ERROR")) {
    drift.push(`cannot read origin/${f.defaultBranch}: ${f.mainHead}`);
    return drift;
  }
  if (f.prodHead !== null && f.prodHead !== undefined) {
    if (f.prodHead.startsWith("ERROR")) {
      drift.push(`deploy target HEAD unreachable over SSH: ${f.prodHead}`);
    } else if (f.prodHead !== f.mainHead) {
      const n = f.behind ? f.behind.split("\n").length : 0;
      drift.push(
        `deploy target (${f.prodHead}) is ${n} commit(s) behind origin/${f.defaultBranch} (${f.mainHead}): MERGED BUT NOT DEPLOYED:\n${f.behind}`,
      );
    }
  }
  for (const [url, status] of Object.entries(f.health || {})) {
    if (status !== "200") drift.push(`${url} = ${status} (expected 200)`);
  }
  if (f.prListError) drift.push(`gh pr list failed: ${f.prListError}`);
  if (f.stalePRs?.length) {
    drift.push(
      `open PRs >${f.staleDays} days old (land or kill): ${f.stalePRs.map((p) => `#${p.number} ${p.title}`).join("; ")}`,
    );
  }
  return drift;
}

/** PURE: render the markdown report. */
export function renderReport({ now, drift, mainHead, prodHead, health, openPRs, worktrees, defaultBranch }) {
  const status = drift.length ? "DRIFT" : "IN SYNC";
  const healthLine = Object.entries(health || {}).map(([u, s]) => `${u}=${s}`).join(" ") || "not configured";
  return `---
name: drift-report
description: AUTO-GENERATED by the daily drift check. Latest deploy-vs-main, health and stale-PR status. Do not hand-edit.
metadata:
  type: project
---

# Drift report: ${now}

**Verdict: ${status}**

- origin/${defaultBranch}: \`${mainHead}\`
- deploy target HEAD: \`${prodHead ?? "not checked"}\`
- health: ${healthLine}
- open PRs: ${openPRs?.length ? openPRs.map((p) => `#${p.number}`).join(", ") : "none"}

${drift.length ? "## Drift found\n\n" + drift.map((d) => `- ${d}`).join("\n") : "No drift: deploy target matches main, health OK, no stale PRs."}

## Worktrees at check time

\`\`\`
${worktrees}
\`\`\`

(Generated by \`tools/drift-check.mjs\`; run it daily from cron.)
`;
}

const run = (cmd, args, opts = {}) => {
  try {
    return execFileSync(cmd, args, { encoding: "utf8", timeout: 30000, stdio: ["ignore", "pipe", "pipe"], ...opts }).trim();
  } catch (e) {
    return `ERROR: ${String(e.message).split("\n")[0]}`;
  }
};

async function status(url) {
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(15000) });
    return String(res.status);
  } catch (e) {
    return `ERROR: ${e.message}`;
  }
}

export async function main(argv = process.argv.slice(2)) {
  const cfg = loadConfig();
  requireKeys(cfg, ["MAIN_WORKTREE"]);
  const cwd = cfg.MAIN_WORKTREE;
  const branch = cfg.DEFAULT_BRANCH;
  const now = new Date().toISOString();

  run("git", ["fetch", "origin", "--quiet"], { cwd });
  const mainHead = run("git", ["rev-parse", "--short", `origin/${branch}`], { cwd });

  let prodHead = null;
  let behind = "";
  if (cfg.PROD_SSH && cfg.PROD_CHECKOUT) {
    prodHead = run("ssh", [
      "-o", "BatchMode=yes", "-o", "ConnectTimeout=10", cfg.PROD_SSH,
      `git -C ${cfg.PROD_CHECKOUT} rev-parse --short HEAD`,
    ]);
    if (!prodHead.startsWith("ERROR") && prodHead !== mainHead) {
      behind = run("git", ["log", "--oneline", `${prodHead}..origin/${branch}`], { cwd });
    }
  }

  const health = {};
  for (const url of [cfg.HEALTH_URL, cfg.STAGING_HEALTH_URL].filter(Boolean)) health[url] = await status(url);

  const prsRaw = run("gh", ["pr", "list", "--state", "open", "--json", "number,title,createdAt", "--limit", "30"], { cwd });
  let openPRs = [];
  let prListError = null;
  try {
    openPRs = JSON.parse(prsRaw);
  } catch {
    prListError = prsRaw;
  }
  const staleDays = Number(cfg.STALE_PR_DAYS) || 2;
  const stalePRs = findStalePRs(openPRs, Date.now(), staleDays);
  const worktrees = run("git", ["worktree", "list"], { cwd });

  const drift = evaluateDrift({ mainHead, prodHead, behind, health, prListError, stalePRs, staleDays, defaultBranch: branch });
  const report = renderReport({ now, drift, mainHead, prodHead, health, openPRs, worktrees, defaultBranch: branch });

  if (argv.includes("--stdout") || !cfg.MEMORY_DIR) {
    console.log(report);
  } else {
    mkdirSync(cfg.MEMORY_DIR, { recursive: true });
    writeFileSync(path.join(cfg.MEMORY_DIR, cfg.DRIFT_REPORT_FILE), report);
  }
  const verdict = drift.length ? "DRIFT" : "IN SYNC";
  console.error(`${now} drift-check: ${verdict}${drift.length ? ` (${drift.length} item(s))` : ""}`);
  for (const d of drift) console.error("  - " + d.split("\n")[0]);
  return drift.length && argv.includes("--strict") ? 1 : 0;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().then((code) => (process.exitCode = code), (err) => {
    console.error(`drift-check: ${err.message}`);
    process.exitCode = 2;
  });
}
